export function findSenzuraProduct(code: string): { category: VeneerProductCategory; subcategory: string | null; product: VeneerProduct } | undefined {
  for (const cat of senzuraProducts) {
    for (const sub of cat.subcategories ?? [{ name: null, products: cat.products }]) {
      const product = sub.products.find((p) => p.code.toLowerCase() === code.toLowerCase());
      if (product) return { category: cat, subcategory: sub.name, product };
    }
  }
  return undefined;
}

